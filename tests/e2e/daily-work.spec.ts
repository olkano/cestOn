import { test, expect } from '@playwright/test';
import { pair } from './helpers.js';

test('opens discovered conversations on desktop and phone, saves and corrects memory, and handles reconnect', async ({ page, context }, info) => {
  await pair(page);
  await page.getByRole('link', { name: 'Chats' }).click();
  await page.getByRole('button', { name: /Fixture conversation/ }).click();
  await expect(page.getByText('The synthetic report is ready.')).toBeVisible();
  await expect(page.getByText('Can’t reply to this conversation from cestOn.', { exact: false })).toBeVisible();
  await page.screenshot({ path: info.outputPath('conversations-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 360, height: 800 });
  await page.getByLabel('Appearance').selectOption('dark');
  await expect(page.getByRole('button', { name: 'Back to conversations' })).toBeVisible();
  await page.getByRole('button', { name: 'Back to conversations' }).click();
  await page.getByRole('link', { name: 'Memory' }).click();
  await page.getByLabel('Your note').fill('Keep the deployment checklist handy.');
  await page.getByRole('button', { name: 'Save note' }).click();
  const note = page.getByRole('article').filter({ hasText: 'Keep the deployment checklist handy.' });
  await expect(note).toBeVisible();
  await note.getByRole('button', { name: 'Edit note' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByLabel('Your note')).toBeFocused();
  await page.getByLabel('Your note').fill('Check the deployment checklist Friday.');
  await page.getByRole('button', { name: 'Save note' }).click();
  const corrected = page.getByRole('article').filter({ hasText: 'Check the deployment checklist Friday.' });
  await expect(corrected).toBeVisible();
  await page.screenshot({ path: info.outputPath('memory-phone-dark.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await context.setOffline(true);
  await expect(corrected.getByRole('button', { name: 'Forget note' })).toBeDisabled();
  await context.setOffline(false);
  await corrected.getByRole('button', { name: 'Forget note' }).click();
  await corrected.getByRole('button', { name: 'Remove from memory' }).click();
  await expect(corrected).toHaveCount(0);
  await page.reload();
  await expect(page.getByText('No notes match.', { exact: false })).toBeVisible();
  await page.getByRole('link', { name: 'Chats' }).click();
  await page.getByRole('button', { name: 'New conversation', exact: true }).click();
  await page.getByLabel('Message in General').fill('Remember: plan the next synthetic review.');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.getByText('Saved in Memory.', { exact: false })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Saved in Memory.', { exact: false })).toBeVisible();
  await page.getByRole('link', { name: 'Open Memory' }).click();
  await expect(page.getByText('plan the next synthetic review.', { exact: true })).toBeVisible();
});
